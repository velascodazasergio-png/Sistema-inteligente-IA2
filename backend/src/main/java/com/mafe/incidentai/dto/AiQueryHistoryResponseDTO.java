package com.mafe.incidentai.dto;

import com.mafe.incidentai.domain.enums.QueryStatus;
import io.swagger.v3.oas.annotations.media.Schema;

import java.time.LocalDateTime;
import java.util.List;

// Output DTO with the full history of AI queries (AiQuery) for an incident
@Schema(description = "Detailed history of a query sent to the AI, including its response, sources and rating")
public record AiQueryHistoryResponseDTO(
        Long aiQueryId,
        Long incidentId,
        String incidentTitle,
        String sentPrompt,
        QueryStatus queryStatus,
        LocalDateTime queriedAt,
        String failureCode,
        String failureMessage,
        AiResponseSummaryDTO aiResponse
) {
    // Summary of the response generated by n8n for the query
    public record AiResponseSummaryDTO(
            Long aiResponseId,
            String suggestedDiagnosis,
            String solutionSteps,
            Double confidenceScore,
            Long processingTimeMs,
            LocalDateTime respondedAt,
            List<SourceSummaryDTO> sources,
            RatingSummaryDTO rating
    ) {}

    // Summary of each source document with its semantic similarity score
    public record SourceSummaryDTO(
            Long id,
            Long knowledgeArticleId,
            String sourceTitle,
            String referenceUrl,
            String citedSnippet,
            Double similarityScore
    ) {}

    // Summary of the rating given by the technician or user
    public record RatingSummaryDTO(
            Long id,
            Integer score,
            Boolean helpful,
            String feedbackComment,
            LocalDateTime ratedAt
    ) {}
}
