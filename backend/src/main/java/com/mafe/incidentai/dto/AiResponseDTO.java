package com.mafe.incidentai.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.Valid;
import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;

import java.util.List;

// DTO that n8n sends back to Spring Boot with the AI diagnosis, sources and similarity scores
@Schema(description = "REST contract that n8n sends back with the AI diagnosis and its source documents")
public record AiResponseDTO(

        @Schema(description = "ID of the original AI query (AiQuery) that triggered the analysis", example = "55")
        @NotNull(message = "AI Query ID is required to link the response")
        Long aiQueryId,

        @Schema(description = "Likely diagnosis generated by the AI agent", example = "Possible UDP port 500/4500 (IPSec NAT-T) block on perimeter firewall")
        @NotBlank(message = "Suggested diagnosis cannot be blank")
        String suggestedDiagnosis,

        @Schema(description = "Recommended steps to resolve the incident", example = "1. Verify UDP 500 and 4500 rules. 2. Restart IKEEXT service on client.")
        String solutionSteps,

        @Schema(description = "Model confidence level between 0.0 and 1.0", example = "0.92")
        @DecimalMin(value = "0.0")
        @DecimalMax(value = "1.0")
        Double confidenceScore,

        @Schema(description = "Total processing time of the n8n workflow, in milliseconds", example = "2340")
        Long processingTimeMs,

        @Schema(description = "List of articles or source documents that support the response (RAG)")
        @Valid
        List<SourceDTO> sources
) {
    // Nested contract for each source document or article cited by the n8n RAG workflow
    @Schema(description = "Source document or knowledge article cited by the AI")
    public record SourceDTO(
            @Schema(description = "Optional ID of the article in the knowledge_articles table", example = "12")
            Long knowledgeArticleId,

            @Schema(description = "Title of the manual, guide or reference ticket", example = "IPSec VPN Runbook v3.1")
            @NotBlank(message = "Source title is required")
            String sourceTitle,

            @Schema(description = "URL or identifier of the document in the knowledge base", example = "https://kb.company.internal/networking/vpn-error-809")
            String referenceUrl,

            @Schema(description = "Text excerpt extracted by the n8n RAG workflow", example = "Error 809 occurs when IKE packets are blocked by NAT-T...")
            String citedSnippet,

            @Schema(description = "Semantic similarity score between the incident and the source (0.0 to 1.0)", example = "0.89")
            @DecimalMin(value = "0.0")
            @DecimalMax(value = "1.0")
            Double similarityScore
    ) {}
}
